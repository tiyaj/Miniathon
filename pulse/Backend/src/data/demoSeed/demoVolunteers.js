/**
 * Seed all 72 demo volunteers for the Hero Event.
 */
export const seedDemoVolunteers = async (heroEvent, zones = [], shifts = []) => {
  const volunteersData = getVolunteersDataset(heroEvent, zones, shifts);

  // Set event and eventId on every volunteer record
  const enriched = volunteersData.map((v) => ({
    ...v,
    event: heroEvent._id,
    eventId: heroEvent._id.toString(),
  }));

  const created = await Volunteer.insertMany(enriched);
  return created;
};
